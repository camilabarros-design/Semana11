document.addEventListener("DOMContentLoaded", () => {
    if (document.getElementById("container-livros")) {
        renderizarHome();
    } else if (document.getElementById("container-detalhes")) {
        renderizarDetalhes();
    }
});

function renderizarHome() {
    const container = document.getElementById("container-livros");
    container.innerHTML = "";

    dados.forEach(item => {
        const card = document.createElement("div");
        card.className = "card";

        card.innerHTML = `
            <a href="detalhes.html?id=${item.id}">
                <img src="${item.imagem}" alt="${item.titulo}" class="card-img">
            </a>
            <div class="card-corpo">
                <span class="tag-categoria">${item.categoria}</span>
                <h2><a href="detalhes.html?id=${item.id}">${item.titulo}</a></h2>
                <p class="autor-card">Por: ${item.autor}</p>
                <p>${item.descricao}</p>
            </div>
        `;
        container.appendChild(card);
    });
}

function renderizarDetalhes() {
    const urlParams = new URLSearchParams(window.location.search);
    const idLivro = parseInt(urlParams.get("id"));

    const livro = dados.find(item => item.id === idLivro);
    const container = document.getElementById("container-detalhes");

    if (!livro) {
        container.innerHTML = `
            <div class="erro-noticia">
                <h2>Livro não encontrado no catálogo!</h2>
                <a href="index.html" class="btn-voltar">Voltar ao Catálogo</a>
            </div>
        `;
        return;
    }

    container.innerHTML = `
        <a href="index.html" class="btn-voltar">← Voltar para o Catálogo</a>
        <article class="conteudo-artigo">
            <span class="tag-categoria">${livro.categoria}</span>
            <h1>${livro.titulo}</h1>
            <div class="metadados">
                Autor: <strong>${livro.autor}</strong> | Ano de Publicação: <strong>${livro.data}</strong>
            </div>
            <div class="layout-detalhe-livro">
                <img src="${livro.imagem}" alt="${livro.titulo}" class="img-livro-detalhe">
                <div class="texto-noticia">
                    <h3>Sinopse Completa:</h3>
                    <p>${livro.conteudo}</p>
                </div>
            </div>
        </article>
    `;
}
